    @Test
    fun gateTableExhaustively() {
        val fx = fixture("gate.json")
        val cases = objects(fx, "cases")
        // Exhaustive: every context (2 lock × 3 role × 2 pin) × every kind —
        // derived from the enum so adding a MutationKind extends the pin.
        assertEquals(2 * 3 * 2 * MutationKind.entries.size, cases.size)
        assertEquals(
            MutationKind.entries.map { it.wire }.toSet(),
            cases.map { it.getString("kind") }.toSet(),
        )
        for (c in cases) {
            val kind = assertNotNull(MutationKind.fromWire(c.getString("kind")))
            val role =
                if (c.isNull("role")) null else HouseholdRole.fromWire(c.getString("role"))
            val verdict = Gate.gateMutation(
                kind,
                GateContext(
                    managedLockOptions = c.getBoolean("managedLockOptions"),
                    role = role,
                    hasPin = c.getBoolean("hasPin"),
                ),
            )
            val expected = c.getJSONObject("verdict")
            val label = "${kind.wire} lock=${c.getBoolean("managedLockOptions")} " +
                "role=${c.opt("role")} pin=${c.getBoolean("hasPin")}"
            if (expected.getBoolean("allowed")) {
                assertEquals(
                    MutationVerdict.Allowed(expected.getBoolean("requiresPin")),
                    verdict,
                    label,
                )
            } else {
                val reason = MutationVerdict.Reason.entries
                    .first { it.wire == expected.getString("reason") }
                assertEquals(MutationVerdict.Refused(reason), verdict, label)
            }
        }

        // Leaving a household never received: gated as that kind's rows,
        // refused under a managed lock, otherwise go in every delay phase.
        assertEquals(Gate.LEAVE_JOIN_PLACEHOLDER_GATED_AS.wire, fx.getString("leaveJoinPlaceholderGatedAs"))
        val placeholder = Household.emptyState("device-a", 0.0)
        val leaveKind = Gate.leaveKind(placeholder)
        assertEquals(Gate.LEAVE_JOIN_PLACEHOLDER_GATED_AS, leaveKind)
        for (c in cases.filter { it.getString("kind") == leaveKind.wire }) {
            val locked = c.getBoolean("managedLockOptions")
            val ctx = GateContext(
                managedLockOptions = locked,
                role = if (c.isNull("role")) null else HouseholdRole.fromWire(c.getString("role")),
                hasPin = c.getBoolean("hasPin"),
            )
            for (phase in DelayPhase.entries) {
                assertEquals(
                    if (locked) MutationStep.Refused(MutationVerdict.Reason.MANAGED_LOCKED) else MutationStep.Go,
                    Delay.decide(DelayAction.Kind(leaveKind), ctx, phase),
                    "placeholder leave lock=$locked role=${c.opt("role")} pin=${c.getBoolean("hasPin")} $phase",
                )
            }
        }
    }

    @Test
    fun delayTable() {
        val fx = fixture("delay.json")
        val allowed = fx.getJSONArray("delayMinutesAllowed")
        assertEquals(Delay.MINUTES_ALLOWED, (0 until allowed.length()).map { allowed.getInt(it) })
        assertEquals(Delay.WINDOW_MS, fx.getLong("windowMs"))
        assertEquals(Delay.SHORTEN_DELAY_GATED_AS.wire, fx.getString("shortenDelayGatedAs"))
        assertEquals(Delay.JOIN_HOUSEHOLD_WAITS_AS.wire, fx.getString("joinHouseholdWaitsAs"))

        val evaluate = objects(fx, "evaluate")
        assertEquals(84, evaluate.size)
        for (c in evaluate) {
            val name = c.getString("name")
            val request = c.optJSONObject("request")?.let { DelayRequest(it.getLong("at")) }
            val got = Delay.evaluate(c.getInt("delayMinutes"), request, c.getLong("now"))
            val r = c.getJSONObject("result")
            val want = DelayEvaluation(
                assertNotNull(DelayPhase.fromWire(r.getString("phase"))),
                r.getLong("remainingMs"),
                r.optJSONObject("request")?.let { DelayRequest(it.getLong("at")) },
            )
            assertEquals(want, got, name)
        }

        val needsWait = objects(fx, "needsWait")
        assertEquals(60, needsWait.size)
        for (c in needsWait) {
            val action = assertNotNull(DelayAction.fromWire(c.getString("action")))
            val phase = assertNotNull(DelayPhase.fromWire(c.getString("phase")))
            assertEquals(c.getBoolean("needsWait"), Delay.needsWait(action, phase), "$action $phase")
        }

        val change = objects(fx, "delayChange")
        assertEquals(80, change.size)
        for (c in change) {
            val from = c.getInt("fromMinutes")
            val to = c.getInt("toMinutes")
            val phase = assertNotNull(DelayPhase.fromWire(c.getString("phase")))
            val action = Delay.changeAction(from, to)
            val label = "$from→$to $phase"
            assertEquals(
                if (c.isNull("action")) null else DelayAction.fromWire(c.getString("action")),
                action,
                label,
            )
            assertEquals(
                c.getBoolean("needsWait"),
                action != null && Delay.needsWait(action, phase),
                label,
            )
        }
    }

